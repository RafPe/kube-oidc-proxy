import puppeteer from 'puppeteer-core';
import assert from 'node:assert/strict';
const origin = process.env.PREVIEW_ORIGIN || 'http://127.0.0.1:4321';
const base = '/kube-oidc-proxy';
const browser = await puppeteer.launch({executablePath:process.env.CHROME_PATH,headless:true});
try {
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror',error=>errors.push(error.message));
  await page.setViewport({width:1440,height:1000});
  await page.goto(`${origin}${base}/interactive/request-flow/`);
  await page.waitForFunction(()=>document.querySelectorAll('header [data-docs-version] option').length === 5);
  assert.equal(await page.$eval('header [data-docs-version]',el=>el.value),'current');
  const originalURL = page.url();
  await page.select('header [data-docs-version]','__toggle_versions__');
  assert.equal(await page.$eval('header [data-docs-version]',el=>el.dataset.expanded),'true');
  assert.equal(await page.$eval('header [data-docs-version]',el=>el.value),'current');
  assert.equal(page.url(),originalURL);
  assert.equal(await page.$eval('header [data-docs-version] option:last-child',el=>el.textContent),'Recent versions');
  await page.select('header [data-docs-version]','__toggle_versions__');
  assert.equal(await page.$eval('header [data-docs-version]',el=>el.dataset.expanded),'false');

  assert.equal(await page.$('.kop-version'),null);
  assert(await page.$eval('header [data-docs-version]',el=>el.previousElementSibling?.getAttribute('href') === 'https://github.com/RafPe/kube-oidc-proxy'));
  await Promise.all([page.waitForNavigation(),page.select('header [data-docs-version]','v2.1.0')]);
  assert.equal(new URL(page.url()).pathname,`${base}/v2.1.0/start/getting-started/`);
  await page.waitForFunction(()=>document.querySelectorAll('header [data-docs-version] option').length === 5);
  assert.equal(await page.$eval('header [data-docs-version]',el=>el.value),'v2.1.0');
  assert.equal(await page.$('.kop-version'),null);
  assert(await page.$eval('header [data-docs-version]',el=>el.previousElementSibling?.getAttribute('href') === 'https://github.com/RafPe/kube-oidc-proxy'));
  await Promise.all([page.waitForNavigation(),page.select('header [data-docs-version]','v2.0.0')]);
  assert.equal(new URL(page.url()).pathname,`${base}/v2.0.0/start/getting-started/`);
  await page.waitForFunction(()=>document.querySelectorAll('header [data-docs-version] option').length === 5);
  await Promise.all([page.waitForNavigation(),page.select('header [data-docs-version]','v1.9.0')]);
  assert.equal(new URL(page.url()).pathname,`${base}/v1.9.0/start/getting-started/`);
  await page.waitForFunction(()=>document.querySelectorAll('header [data-docs-version] option').length === 5);
  await page.setViewport({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Archive overflows on mobile');
  await page.click('button[popovertarget="starlight__sidebar"]');
  assert(await page.$eval('.mobile-preferences [data-docs-version]',el=>el.checkVisibility()));
  await page.select('.mobile-preferences [data-docs-version]','__toggle_versions__');
  assert.equal(await page.$eval('.mobile-preferences [data-docs-version]',el=>el.dataset.expanded),'true');
  await Promise.all([page.waitForNavigation(),page.select('.mobile-preferences [data-docs-version]','current')]);
  assert.equal(new URL(page.url()).pathname,`${base}/start/getting-started/`);
  await page.waitForFunction(()=>document.querySelectorAll('header [data-docs-version] option').length === 5);
  await page.setViewport({width:1440,height:1000});
  await page.screenshot({path:'/tmp/docs-header-version.png'});
  assert.deepEqual(errors,[]);
  console.log('Version browser checks passed: all tags, page fallback, return to current docs, and mobile layout.');
} finally {await browser.close();}
